print("An,Dương,Vương,Ba,Đình")

import pandas as pd

# Tạo danh sách gồm 10 tên
danh_sach_ten = [
    "An", "Dương", "Vương", "Ba", "Đình",
    "Lan", "Mai", "Minh", "Tuấn", "Như"
]

# Tạo điểm chuyên cần
điểm_chuyên_cần = []
print("Nhập điểm chuyên cần cho từng học sinh :")
for ten in danh_sach_ten:
    điểm = int(input (f"Nhập điểm chuyên cần cho {ten}) :"))
    điểm_chuyên_cần.append(điểm)
# Tạo điểm giữa kỳ
điểm_giữa_kỳ =[]
print("Nhập điểm giữa kỳ cho từng học sinh :")
for ten in danh_sach_ten:
    điểm = int(input (f"Nhập điểm giữa kỳ cho {ten}) :"))
    điểm_giữa_kỳ.append(điểm)
# Tạo điểm cuối kỳ
điểm_cuối_kỳ =[]
print("Nhập điểm cuối kỳ cho từng học sinh :")
for ten in danh_sach_ten:
    điểm = int(input (f"Nhập điểm cuối kỳ cho {ten}) :"))
    điểm_cuối_kỳ.append(điểm)
# Xếp loại học sinh
def phan_loai(điểm_tổng_kết):
    if điểm_tổng_kết >=8.5:
        return "Giỏi"
    elif 7 <= điểm_tổng_kết < 8.5:
        return "Khá"
    elif 5 <= điểm_tổng_kết < 7:
        return "Trung bình"
    else:
        return "Yếu"

# Tạo DataFrame từ danh sách
df = pd.DataFrame({
    "Tên": danh_sach_ten,
    "Điểm chuyên cần": điểm_chuyên_cần,
    "Điểm giữa kỳ": điểm_giữa_kỳ,
    "Điểm cuối kỳ": điểm_cuối_kỳ
})
# Thêm cột điểm chuyên cần vào DataFrame
df["Điểm chuyên cần"] = điểm_chuyên_cần
# Thêm cột điểm giữa kỳ vào DataFrame
df["Điểm giữa kỳ"] = điểm_giữa_kỳ
# Thêm cột điểm cuối kỳ cào DatFrame
df["Điểm cuối kỳ"] =điểm_cuối_kỳ
# Thêm cột điểm Tổng kết vào DataFrame
df["Điểm tổng kết"] =(
                      df['Điểm chuyên cần']*0.2
                      +df["Điểm giữa kỳ"]*0.3
                      +df["Điểm cuối kỳ"]*0.5
)
# Thêm cột xếp loại
df["Xếp loại"] = df["Điểm tổng kết"].apply(phan_loai)
# Hiển thị DataFrame
display(df)

print("Thống Kê")
# Điểm tổng kết trung bình của lớp
trung_bình = df["Điểm tổng kết"].mean()
print(f"Điểm tổng kết trung bình của lớp là : {trung_bình:.2f}")

# Sinh viên có điểm tổng kết cao nhất
sinh_viên_cao = df.loc[df["Điểm tổng kết"].idxmax()]

# Sinh viên có điểm tổng kết thấp nhất
sinh_viên_thấp = df.loc[df["Điểm tổng kết"].idxmin()]

# Số sinh viên đạt (>=5)
so_sinh_viên_đạt = (df["Điểm tổng kết"] >= 5).sum()

# Tự động điền dữ liệu vào bảng thống kê
bang_thong_ke = pd.DataFrame({
    "Chỉ tiêu": [
        "Điểm tổng kết trung bình cả lớp",
        f"Điểm tổng kết cao nhất ({sinh_viên_cao['Tên']})",
        f"Điểm tổng kết thấp nhất ({sinh_viên_thấp['Tên']})",
        "Số lượng sinh viên đạt (>=5)"
    ],
    "Số liệu": [
        round(trung_bình, 2),
        sinh_viên_cao["Điểm tổng kết"],
        sinh_viên_thấp["Điểm tổng kết"],
        so_sinh_viên_đạt
    ]
})

# Hiển thị bảng chạy kết quả
display(bang_thong_ke)

import matplotlib.pyplot as plt

# 1. Khởi tạo và đặt kích thước cho biểu đồ
plt.figure(figsize=(10, 6))

# 2. Vẽ biểu đồ cột đứng tự động lấy dữ liệu từ DataFrame
plt.bar(df['Tên'], df['Điểm tổng kết'], color='skyblue', edgecolor='black')

# 3. Thêm tiêu đề và nhãn cho các trục tọa độ
plt.title('Biểu đồ thể hiện Điểm tổng kết của 10 sinh viên', fontsize=14, fontweight='bold')
plt.xlabel('Tên sinh viên', fontsize=12)
plt.ylabel('Điểm tổng kết', fontsize=12)

# Đặt giới hạn trục tung từ 0 đến 10 để dễ quan sát
plt.ylim(0, 10)

# Thêm lưới mờ cho trục tung
plt.grid(axis='y', linestyle='--', alpha=0.7)

# 4. Tự động điền số điểm cụ thể lên đầu mỗi cột
for index, row in df.iterrows():
    plt.text(index, row['Điểm tổng kết'] + 0.15, f"{row['Điểm tổng kết']:.1f}", ha='center', va='bottom', fontsize=10)

# Hiển thị biểu đồ
plt.tight_layout()
plt.show()